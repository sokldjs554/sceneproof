"""Writes tools/event_labeler/zones.js from configs/bench/zones.yaml (the labeler page reads it with a plain
<script> tag, so it works from file:// without a server)."""

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
z = yaml.safe_load((ROOT / "configs" / "bench" / "zones.yaml").read_text())
out = ROOT / "tools" / "event_labeler" / "zones.js"
out.write_text("// generated by scripts/build_labeler_zones.py from configs/bench/zones.yaml — do not edit\n"
               f"window.BENCH_ZONES = {json.dumps({'rules': z['rules'], 'sites': z['sites']}, ensure_ascii=False, indent=1)};\n")
print(f"wrote {out}")
